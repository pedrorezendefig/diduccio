CREATE TABLE public.uploads_piscina (
  id bigint generated by default as identity primary key,
  id_piscina text,
  nome_arquivo text,
  url_drive text,
  file_id text,
  created_at timestamptz DEFAULT now(),
  updated_at timestamptz NOT NULL DEFAULT now()
);
ALTER TABLE public.uploads_piscina ENABLE ROW LEVEL SECURITY;
CREATE TRIGGER trg_uploads_piscina_updated_at BEFORE UPDATE ON public.uploads_piscina FOR EACH ROW EXECUTE FUNCTION public.tocar_updated_at();
CREATE INDEX idx_uploads_piscina_created_at ON public.uploads_piscina (created_at);
CREATE INDEX idx_uploads_piscina_updated_at ON public.uploads_piscina (updated_at);
