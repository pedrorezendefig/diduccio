-- Permite cadastrar usuário novo.
--
-- `usuarios.id` veio da planilha como `bigint PRIMARY KEY` sem default: os ids
-- eram gerados pelo Apps Script. Verificado: um insert sem id falha com
-- "null value in column id violates not-null constraint" — ou seja, a tela de
-- cadastro quebraria no primeiro uso.
--
-- BY DEFAULT e não ALWAYS: a carga da migração grava ids explícitos, e um
-- reprocessamento da planilha precisa continuar funcionando. ALWAYS recusaria.
alter table public.usuarios
  alter column id add generated by default as identity;

-- A sequência nasce em 1 e colidiria com os ids 1..6 que já existem. Começa
-- depois do maior id em uso, calculado agora em vez de fixado no arquivo.
select setval(
  pg_get_serial_sequence('public.usuarios', 'id'),
  coalesce((select max(id) from public.usuarios), 0) + 1,
  false
);
