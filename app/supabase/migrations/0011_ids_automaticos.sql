-- Torna automático o `id` de todas as tabelas que vieram da planilha.
--
-- Na planilha quem gerava os ids era o Apps Script; a carga da migração
-- trouxe os valores prontos e as colunas ficaram `bigint PRIMARY KEY` sem
-- default. Consequência verificada com sessão real: qualquer insert falha com
-- "null value in column id violates not-null constraint".
--
-- Sem isto, TODA gravação do app quebraria depois de convertida — as 22 telas.
-- O 0009 já resolveu `usuarios`; este arquivo faz o resto.
--
-- Só tabelas de id numérico. As de id textual (assembleias, compras,
-- compras_produtos, uploads_*) usam identificadores com significado
-- ("ATA-...", "COMP-...", "UPC-...-0") gerados pela aplicação — dar um default
-- a elas produziria ids sem sentido. A conversão dessas telas precisa continuar
-- gerando o id no cliente, como o Apps Script fazia.

do $$
declare
  t record;
  seq text;
begin
  for t in
    select c.table_name
      from information_schema.columns c
      join information_schema.tables tb
        on tb.table_schema = c.table_schema and tb.table_name = c.table_name
     where c.table_schema = 'public'
       and c.column_name  = 'id'
       and c.data_type    = 'bigint'
       and c.column_default is null
       and c.is_identity  = 'NO'
       and tb.table_type  = 'BASE TABLE'
  loop
    execute format(
      'alter table public.%I alter column id add generated by default as identity',
      t.table_name);

    -- BY DEFAULT e não ALWAYS: recarregar a planilha grava ids explícitos, e
    -- ALWAYS recusaria. A sequência começa depois do maior id em uso, senão
    -- colide com o que já está lá.
    seq := pg_get_serial_sequence('public.' || quote_ident(t.table_name), 'id');
    execute format(
      'select setval(%L, coalesce((select max(id) from public.%I), 0) + 1, false)',
      seq, t.table_name);

    raise notice 'id automático: %', t.table_name;
  end loop;
end $$;
