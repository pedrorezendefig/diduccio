-- Completa o 0011 nas tabelas que estavam vazias na planilha.
--
-- O gerador de schema da fase 1A inferia o tipo da chave a partir dos dados.
-- Para aba vazia não havia o que inspecionar, e `tipoDaChave([])` devolvia
-- "text" — então entregas, entregadores, multas e as demais vazias nasceram
-- com `id text` sem default. O 0011 procurava só `bigint` e passou por elas.
--
-- Verificado com sessão real de síndico: 11 de 15 tabelas gravaram, e as 4 que
-- falharam eram exatamente as vazias.
--
-- Converter para bigint identity só é seguro porque estão vazias: não há valor
-- para reinterpretar. A migração checa isso linha a linha em vez de confiar na
-- lista — se alguma tiver ganhado dado desde então, ela é pulada com aviso.
--
-- Ficam de fora as tabelas de id textual COM dados (assembleias, compras,
-- compras_produtos, uploads_festas, uploads_compras): ali o id tem significado
-- ("ATA-...", "COMP-...") e é gerado pela aplicação.

do $$
declare
  t record;
  linhas bigint;
begin
  for t in
    select c.table_name
      from information_schema.columns c
      join information_schema.tables tb
        on tb.table_schema = c.table_schema and tb.table_name = c.table_name
     where c.table_schema = 'public'
       and c.column_name  = 'id'
       and c.data_type    = 'text'
       and c.column_default is null
       and c.is_identity  = 'NO'
       and tb.table_type  = 'BASE TABLE'
  loop
    execute format('select count(*) from public.%I', t.table_name) into linhas;

    if linhas > 0 then
      raise notice 'pulada (% linhas, id textual com significado): %', linhas, t.table_name;
      continue;
    end if;

    execute format('alter table public.%I alter column id type bigint using null', t.table_name);
    execute format(
      'alter table public.%I alter column id add generated by default as identity',
      t.table_name);

    raise notice 'id automático: %', t.table_name;
  end loop;
end $$;
