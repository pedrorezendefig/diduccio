-- A retirada de encomenda vira registro assinado, e o livro de papel sai.
--
-- Uma linha por EVENTO de retirada, não por encomenda: o comprovante que se vai
-- querer mostrar um dia é "o que essa pessoa levou naquela hora". Por encomenda,
-- isso ficaria espalhado por N linhas que só um horário parecido aproxima.
--
-- Desenho completo em docs/superpowers/specs/2026-08-17-retirada-de-encomenda-design.md

create table if not exists public.retiradas (
  id                 bigint generated by default as identity primary key,
  id_unidade         bigint,
  retirado_por_nome  text not null,
  retirado_por_cpf   text not null,
  -- O titular da encomenda, quando conhecido. Diferente de `retirado_por_*`:
  -- quando a filha desce com o código da mãe, `id_morador` é a mãe e
  -- `retirado_por_nome` é a filha. O registro diz que a encomenda era de uma
  -- pessoa e saiu com outra, que é exatamente o fato a guardar.
  id_morador         bigint,
  via                text not null check (via in ('codigo', 'identificacao')),
  assinatura_caminho text not null,
  observacao         text,
  entregue_por       text,
  created_at         timestamptz not null default now(),
  updated_at         timestamptz not null default now()
);

alter table public.retiradas enable row level security;

drop trigger if exists trg_retiradas_updated_at on public.retiradas;
create trigger trg_retiradas_updated_at before update on public.retiradas
  for each row execute function public.tocar_updated_at();

create index if not exists idx_retiradas_created_at on public.retiradas (created_at);
create index if not exists idx_retiradas_id_unidade on public.retiradas (id_unidade);

-- A ligação. Uma encomenda é retirada uma vez só, então não há tabela de
-- ligação: N encomendas apontam para 1 retirada.
alter table public.entregas
  add column if not exists id_retirada bigint references public.retiradas(id);

create index if not exists idx_entregas_id_retirada on public.entregas (id_retirada);

-- ---------------------------------------------------------------------------
-- RLS: o porteiro registra, e o que registrou não volta atrás
-- ---------------------------------------------------------------------------
-- Mesma regra do 0026, pelo mesmo motivo: este registro É o livro, e a
-- fragilidade do livro de papel é justamente que dá para arrancar a folha.
drop policy if exists retiradas_ler    on public.retiradas;
drop policy if exists retiradas_criar  on public.retiradas;
drop policy if exists retiradas_editar on public.retiradas;
drop policy if exists retiradas_apagar on public.retiradas;

create policy retiradas_ler on public.retiradas
  for select to authenticated
  using (public.eh_administrativo() or public.eh_porteiro());

create policy retiradas_criar on public.retiradas
  for insert to authenticated
  with check (public.eh_administrativo() or public.eh_porteiro());

-- Só a administração alcança o UPDATE, e mesmo ela só muda a observação — o
-- gatilho abaixo é quem garante isso. O porteiro não entra aqui de forma alguma.
create policy retiradas_editar on public.retiradas
  for update to authenticated
  using (public.eh_administrativo());

create policy retiradas_apagar on public.retiradas
  for delete to authenticated
  using (public.eh_sindico());

-- ---------------------------------------------------------------------------
-- Só a observação admite correção
-- ---------------------------------------------------------------------------
-- Quem retirou, quando, o que levou e a assinatura são fatos: ficam congelados
-- no instante em que nascem. A observação é a única coisa ali que é anotação, e
-- anotação se corrige.
--
-- Compara a linha inteira em jsonb, e não coluna a coluna: lista escrita à mão
-- protege o que existia no dia em que foi escrita, e a coluna acrescentada no
-- ano que vem nasceria aberta. Foi o engano cometido na primeira versão do
-- gatilho do 0026, que esquecia created_by, created_at e updated_at.
--
-- `updated_at` fica de fora porque o gatilho `tocar_updated_at` já a carimbou
-- antes deste rodar: os dois são BEFORE UPDATE e a ordem é alfabética, então
-- trg_retiradas_updated_at vem antes de trg_retirada_so_corrige_observacao.
create or replace function public.retirada_so_corrige_observacao()
returns trigger language plpgsql security definer
set search_path = public as $$
declare
  alterados text;
begin
  select string_agg(chave, ', ' order by chave) into alterados
    from jsonb_each(to_jsonb(new) - 'observacao' - 'updated_at') as campo(chave, valor)
   where campo.valor is distinct from (to_jsonb(old) -> campo.chave);

  if alterados is not null then
    raise exception 'Numa retirada só a observação pode ser corrigida. Não pode alterar: %', alterados
      using errcode = 'check_violation';
  end if;
  return new;
end $$;

revoke execute on function public.retirada_so_corrige_observacao() from public;
revoke execute on function public.retirada_so_corrige_observacao() from anon;

drop trigger if exists trg_retirada_so_corrige_observacao on public.retiradas;
create trigger trg_retirada_so_corrige_observacao
  before update on public.retiradas
  for each row execute function public.retirada_so_corrige_observacao();

-- ---------------------------------------------------------------------------
-- O bucket aprende a pasta `retiradas`
-- ---------------------------------------------------------------------------
-- Sem isto o porteiro não grava: as duas funções caem num `else` que só libera
-- administração. Falha fechada, que é o lado certo de falhar — mas precisa de
-- ajuste explícito.
create or replace function public.pode_ler_anexo(nome text)
returns boolean language sql stable
set search_path = public as $$
  select case public.modulo_do_anexo(nome)
    when 'encomendas'  then public.eh_administrativo() or public.eh_porteiro()
    when 'retiradas'   then public.eh_administrativo() or public.eh_porteiro()
    when 'assembleias' then public.eh_administrativo() or public.eh_conselheiro()
    else public.eh_administrativo()
  end;
$$;

create or replace function public.pode_escrever_anexo(nome text)
returns boolean language sql stable
set search_path = public as $$
  select case public.modulo_do_anexo(nome)
    when 'encomendas' then public.eh_administrativo() or public.eh_porteiro()
    when 'retiradas'  then public.eh_administrativo() or public.eh_porteiro()
    else public.eh_administrativo()
  end;
$$;

-- O 0018 fez apagar seguir escrita. Certo para foto de encomenda — o arquivo
-- substituído é lixo por definição, e deixá-lo no bucket é atestado médico de
-- alguém continuando alcançável por URL assinada. Errado para comprovante: quem
-- operou não pode desfazer a prova do que operou.
drop policy if exists anexos_apagar on storage.objects;
create policy anexos_apagar on storage.objects
  for delete to authenticated
  using (
    bucket_id = 'anexos'
    and case public.modulo_do_anexo(name)
          when 'retiradas' then public.eh_sindico()
          else public.pode_escrever_anexo(name)
        end
  );

-- ---------------------------------------------------------------------------
-- A gravação, em transação única
-- ---------------------------------------------------------------------------
-- Em duas chamadas separadas, uma falha no meio deixaria o morador tendo
-- assinado por encomendas que continuam constando como pendentes na portaria.
--
-- `security invoker` (o padrão, explicitado de propósito): o RLS de `retiradas`
-- e de `entregas` continua valendo. Esta função organiza a transação, não
-- concede poder nenhum — ao contrário das `security definer` do projeto, que
-- existem para atravessar o RLS.
create or replace function public.registrar_retirada(
  p_id_unidade         bigint,
  p_retirado_por_nome  text,
  p_retirado_por_cpf   text,
  p_id_morador         bigint,
  p_via                text,
  p_assinatura_caminho text,
  p_observacao         text,
  p_entregas           bigint[],
  p_entregue_por       text
) returns bigint
language plpgsql
security invoker
set search_path = public as $$
declare
  nova_id     bigint;
  atualizadas int;
  quantas     int := coalesce(array_length(p_entregas, 1), 0);
begin
  if coalesce(btrim(p_assinatura_caminho), '') = '' then
    raise exception 'A retirada exige assinatura.' using errcode = 'check_violation';
  end if;

  -- Assinatura sem nada ligado e sem explicação é um comprovante que não prova
  -- nada — e é pior que não existir, porque parece registro.
  if quantas = 0 and coalesce(btrim(p_observacao), '') = '' then
    raise exception 'Sem encomenda marcada, a observação é obrigatória.'
      using errcode = 'check_violation';
  end if;

  insert into public.retiradas (
    id_unidade, retirado_por_nome, retirado_por_cpf, id_morador,
    via, assinatura_caminho, observacao, entregue_por
  ) values (
    p_id_unidade,
    btrim(p_retirado_por_nome),
    regexp_replace(coalesce(p_retirado_por_cpf, ''), '\D', '', 'g'),
    p_id_morador,
    p_via,
    p_assinatura_caminho,
    nullif(btrim(coalesce(p_observacao, '')), ''),
    p_entregue_por
  ) returning id into nova_id;

  if quantas > 0 then
    -- `id_retirada is null` no where: impede roubar encomenda que já saiu por
    -- outra retirada. Duas telas dando baixa no mesmo pacote ao mesmo tempo é
    -- exatamente o caso em que o registro passaria a mentir — e a contagem
    -- abaixo é o que transforma isso em erro em vez de baixa silenciosa pela
    -- metade.
    update public.entregas
       set id_retirada  = nova_id,
           status       = 'Entregue',
           data_saida   = now(),
           entregue_por = p_entregue_por,
           nome_morador = btrim(p_retirado_por_nome),
           cpf_morador  = regexp_replace(coalesce(p_retirado_por_cpf, ''), '\D', '', 'g')
     where id = any(p_entregas)
       and id_retirada is null;

    get diagnostics atualizadas = row_count;
    if atualizadas <> quantas then
      raise exception 'Alguma encomenda já foi retirada ou não existe (% de % atualizadas).',
        atualizadas, quantas using errcode = 'check_violation';
    end if;
  end if;

  return nova_id;
end $$;

-- EXECUTE nasce aberto a PUBLIC, e PUBLIC inclui anon. Já foi esquecido duas
-- vezes neste projeto — e `revoke from anon` sozinho não resolve, porque o
-- privilégio vem de PUBLIC.
revoke execute on function public.registrar_retirada(bigint,text,text,bigint,text,text,text,bigint[],text) from public;
revoke execute on function public.registrar_retirada(bigint,text,text,bigint,text,text,text,bigint[],text) from anon;
grant  execute on function public.registrar_retirada(bigint,text,text,bigint,text,text,text,bigint[],text) to authenticated;

-- ---------------------------------------------------------------------------
-- `entregas_recebimento` sai de cena
-- ---------------------------------------------------------------------------
-- Tabela vazia (0 linhas), criada para a foto de recebimento e nunca usada. É
-- exatamente o lugar que esta funcionalidade ocupa, e mantê-la é convidar
-- alguém a preencher as duas.
drop table if exists public.entregas_recebimento;
