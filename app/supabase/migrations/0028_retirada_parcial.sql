-- Retirada parcial: o morador leva parte dos volumes e o resto fica.
--
-- Antes, marcar 2 de 3 volumes não tinha para onde ir: ou a encomenda era
-- encerrada como "Entregue" — afirmando que a caixa deixada na prateleira saiu,
-- assinada, com CPF e hora — ou ficava "Pendente" como se nada tivesse
-- acontecido, e a assinatura recolhida não apontava para encomenda nenhuma.
--
-- Agora existe o meio-termo: status 'Parcialmente entregue', a contagem do que
-- saiu, e a ligação entre a retirada assinada e a encomenda que ela tocou.
--
-- A encomenda NÃO é fechada: `id_retirada` continua nulo, então ela segue
-- aparecendo na portaria e pode sair de novo numa segunda retirada, com a sua
-- própria assinatura.

-- Rodar com o app fechado.
--
-- `add column` pede AccessExclusiveLock em `entregas`, que conflita com a
-- leitura mais banal do PostgREST. Com o editor SQL rodando tudo numa
-- transação só e a tela aberta noutra aba, os dois esperam um pelo outro e o
-- Postgres mata a migração por deadlock — foi o que aconteceu na primeira
-- tentativa desta aqui.
--
-- `lock_timeout` transforma isso em "não consegui o lock em 10s", que é um
-- erro claro e que não deixa metade aplicada. O script inteiro é re-executável:
-- `if not exists` nas criações, `create or replace` na função, e `drop policy
-- if exists` antes de cada policy.
set lock_timeout = '10s';

alter table public.entregas
  add column if not exists volumes_retirados int not null default 0;

-- ---------------------------------------------------------------------------
-- O que cada retirada tirou de cada encomenda
-- ---------------------------------------------------------------------------
-- Para a encomenda fechada, `entregas.id_retirada` já é a ligação. Para a
-- parcial não havia nenhuma: a assinatura existia solta e o próximo porteiro
-- não tinha como saber quantos volumes ainda deve. Uma encomenda pode aparecer
-- aqui mais de uma vez — é o histórico de saídas dela.
create table if not exists public.retirada_itens (
  id          bigint generated by default as identity primary key,
  id_retirada bigint not null references public.retiradas(id) on delete cascade,
  id_entrega  bigint not null references public.entregas(id),
  volumes     int not null check (volumes > 0),
  created_at  timestamptz not null default now()
);

create index if not exists idx_retirada_itens_id_retirada on public.retirada_itens (id_retirada);
create index if not exists idx_retirada_itens_id_entrega  on public.retirada_itens (id_entrega);

alter table public.retirada_itens enable row level security;

-- Privilégio de tabela nova em `public` nasce aberto ao anônimo por padrão do
-- Supabase. O RLS abaixo já barraria, mas privilégio que não precisa existir é
-- privilégio que não deve existir.
revoke all on public.retirada_itens from anon;

-- ---------------------------------------------------------------------------
-- RLS: mesma regra da retirada — quem registra não volta atrás
-- ---------------------------------------------------------------------------
drop policy if exists retirada_itens_ler    on public.retirada_itens;
drop policy if exists retirada_itens_criar  on public.retirada_itens;
drop policy if exists retirada_itens_apagar on public.retirada_itens;

create policy retirada_itens_ler on public.retirada_itens
  for select to authenticated
  using (public.eh_administrativo() or public.eh_porteiro());

create policy retirada_itens_criar on public.retirada_itens
  for insert to authenticated
  with check (public.eh_administrativo() or public.eh_porteiro());

-- Sem policy de UPDATE de propósito: sem policy, ninguém atualiza. O que saiu
-- naquela retirada é fato, não anotação.
create policy retirada_itens_apagar on public.retirada_itens
  for delete to authenticated
  using (public.eh_sindico());

-- ---------------------------------------------------------------------------
-- A gravação aprende o caso parcial
-- ---------------------------------------------------------------------------
-- A função antiga PRECISA sair antes: acrescentar um parâmetro com default
-- criaria uma sobrecarga, e a chamada com nove argumentos passaria a casar com
-- as duas — erro de ambiguidade em produção, no meio de uma retirada.
drop function if exists public.registrar_retirada(bigint,text,text,bigint,text,text,text,bigint[],text);

create or replace function public.registrar_retirada(
  p_id_unidade         bigint,
  p_retirado_por_nome  text,
  p_retirado_por_cpf   text,
  p_id_morador         bigint,
  p_via                text,
  p_assinatura_caminho text,
  p_observacao         text,
  p_entregas           bigint[],
  p_entregue_por       text,
  -- [{"id": 12, "volumes": 2}] — o que saiu de encomendas que NÃO fecharam.
  p_parciais           jsonb default '[]'::jsonb
) returns bigint
language plpgsql
security invoker
set search_path = public as $$
declare
  nova_id     bigint;
  atualizadas int;
  quantas     int := coalesce(array_length(p_entregas, 1), 0);
  parciais    jsonb := coalesce(p_parciais, '[]'::jsonb);
  quantos_par int := jsonb_array_length(parciais);
begin
  if coalesce(btrim(p_assinatura_caminho), '') = '' then
    raise exception 'A retirada exige assinatura.' using errcode = 'check_violation';
  end if;

  -- Assinatura sem nada ligado e sem explicação é um comprovante que não prova
  -- nada — e é pior que não existir, porque parece registro. Uma retirada só
  -- parcial JÁ está ligada a uma encomenda, então ela conta como "algo ligado".
  if quantas = 0 and quantos_par = 0 and coalesce(btrim(p_observacao), '') = '' then
    raise exception 'Sem encomenda marcada, a observação é obrigatória.'
      using errcode = 'check_violation';
  end if;

  insert into public.retiradas (
    id_unidade, retirado_por_nome, retirado_por_cpf, id_morador,
    via, assinatura_caminho, observacao, entregue_por
  ) values (
    p_id_unidade,
    btrim(p_retirado_por_nome),
    regexp_replace(coalesce(p_retirado_por_cpf, ''), '\D', '', 'g'),
    p_id_morador,
    p_via,
    p_assinatura_caminho,
    nullif(btrim(coalesce(p_observacao, '')), ''),
    p_entregue_por
  ) returning id into nova_id;

  if quantas > 0 then
    -- `id_retirada is null` no where: impede roubar encomenda que já saiu por
    -- outra retirada. Duas telas dando baixa no mesmo pacote ao mesmo tempo é
    -- exatamente o caso em que o registro passaria a mentir — e a contagem
    -- abaixo é o que transforma isso em erro em vez de baixa silenciosa pela
    -- metade.
    update public.entregas
       set id_retirada  = nova_id,
           status       = 'Entregue',
           data_saida   = now(),
           entregue_por = p_entregue_por,
           nome_morador = btrim(p_retirado_por_nome),
           cpf_morador  = regexp_replace(coalesce(p_retirado_por_cpf, ''), '\D', '', 'g')
     where id = any(p_entregas)
       and id_retirada is null;

    get diagnostics atualizadas = row_count;
    if atualizadas <> quantas then
      raise exception 'Alguma encomenda já foi retirada ou não existe (% de % atualizadas).',
        atualizadas, quantas using errcode = 'check_violation';
    end if;
  end if;

  if quantos_par > 0 then
    -- A encomenda continua ABERTA: `id_retirada` fica nulo e o status vira
    -- parcial, então ela segue na portaria e pode sair de novo depois.
    update public.entregas en
       set status            = 'Parcialmente entregue',
           volumes_retirados = en.volumes_retirados + d.volumes
      from (
        select (e->>'id')::bigint as id, (e->>'volumes')::int as volumes
          from jsonb_array_elements(parciais) as e
      ) d
     where en.id = d.id
       and en.id_retirada is null
       and d.volumes > 0;

    get diagnostics atualizadas = row_count;
    if atualizadas <> quantos_par then
      raise exception 'Alguma encomenda parcial já foi retirada ou não existe (% de %).',
        atualizadas, quantos_par using errcode = 'check_violation';
    end if;

    insert into public.retirada_itens (id_retirada, id_entrega, volumes)
    select nova_id, (e->>'id')::bigint, (e->>'volumes')::int
      from jsonb_array_elements(parciais) as e
     where (e->>'volumes')::int > 0;
  end if;

  return nova_id;
end $$;

-- EXECUTE nasce aberto a PUBLIC, e PUBLIC inclui anon. Já foi esquecido duas
-- vezes neste projeto — e `revoke from anon` sozinho não resolve, porque o
-- privilégio vem de PUBLIC.
revoke execute on function public.registrar_retirada(bigint,text,text,bigint,text,text,text,bigint[],text,jsonb) from public;
revoke execute on function public.registrar_retirada(bigint,text,text,bigint,text,text,text,bigint[],text,jsonb) from anon;
grant  execute on function public.registrar_retirada(bigint,text,text,bigint,text,text,text,bigint[],text,jsonb) to authenticated;
