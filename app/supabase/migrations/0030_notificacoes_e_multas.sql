-- Notificações e multas por descumprimento de norma condominial.
--
-- Uma tabela só, com `tipo`. Duas tabelas separadas fariam a contagem virar um
-- union, e a regra que este módulo existe para sustentar — a cada 2
-- notificações a 3ª infração é multa — ficaria espalhada por dois lugares.
--
-- A CONTAGEM NÃO É COLUNA. É derivada: notificações da unidade criadas depois
-- da última multa daquela unidade. Contador materializado dessincroniza no dia
-- em que alguém apaga um registro, e aí o sistema passa a afirmar um número que
-- não confere com as linhas. A consulta não tem como mentir.
--
-- A âncora é a UNIDADE, não o morador: o condômino responde pelos atos de quem
-- mora e de quem visita a unidade, então trocar de inquilino não zera histórico.

create table if not exists public.notificacoes (
  id            bigint generated by default as identity primary key,
  tipo          text not null check (tipo in ('NOTIFICACAO', 'MULTA')),
  id_unidade    bigint not null,
  -- Quem foi nomeado, quando está cadastrado. Fica separado de `destinatario`
  -- porque nem todo notificado é morador cadastrado — visitante e inquilino
  -- recém-chegado aparecem na carta e não têm linha em `moradores`.
  id_morador    bigint,
  destinatario  text not null,
  assunto       text not null,
  descricao     text not null,
  -- A data do FATO. Diferente de `created_at`, que é quando se cadastrou, e
  -- diferente da data da carta, que é a de emissão. As três divergem: a
  -- infração é de segunda, o síndico cadastra na quarta, a carta sai na quinta.
  ocorrido_em   date,
  -- Preenchida SÓ quando a 3ª infração saiu como notificação em vez de multa.
  -- É o registro de que alguém decidiu contra a regra, e por quê. Sem isto a
  -- exceção não deixaria rastro nenhum.
  justificativa text,
  created_at    timestamptz not null default now(),
  created_by    text,
  updated_at    timestamptz not null default now()
);

alter table public.notificacoes enable row level security;

drop trigger if exists trg_notificacoes_updated_at on public.notificacoes;
create trigger trg_notificacoes_updated_at before update on public.notificacoes
  for each row execute function public.tocar_updated_at();

-- A consulta que a tela faz o tempo todo é "o histórico desta unidade, do mais
-- novo para o mais velho", que é exatamente a contagem.
create index if not exists idx_notificacoes_unidade_data
  on public.notificacoes (id_unidade, created_at desc);
create index if not exists idx_notificacoes_tipo on public.notificacoes (tipo);

-- ---------------------------------------------------------------------------
-- RLS
-- ---------------------------------------------------------------------------
-- Notificar é ato do síndico (art. 1.348 do Código Civil), mas quem digita
-- costuma ser o auxiliar. Por isso criar é administrativo, e desfazer não:
-- apagar uma notificação apaga a contagem que leva à multa, e isso é decisão
-- de quem responde pelo condomínio.
--
-- Porteiro e conselheiro ficam de fora inteiramente — aqui há descrição de
-- conduta de morador identificado.
drop policy if exists notificacoes_ler    on public.notificacoes;
drop policy if exists notificacoes_criar  on public.notificacoes;
drop policy if exists notificacoes_editar on public.notificacoes;
drop policy if exists notificacoes_apagar on public.notificacoes;

create policy notificacoes_ler on public.notificacoes
  for select to authenticated
  using (public.eh_administrativo());

create policy notificacoes_criar on public.notificacoes
  for insert to authenticated
  with check (public.eh_administrativo());

create policy notificacoes_editar on public.notificacoes
  for update to authenticated
  using (public.eh_sindico());

create policy notificacoes_apagar on public.notificacoes
  for delete to authenticated
  using (public.eh_sindico());

-- O anônimo não tem o que fazer aqui. Sem isto, a policy acima é a única
-- barreira, e uma policy é mais fácil de derrubar por engano que um revoke.
revoke all on public.notificacoes from anon;
