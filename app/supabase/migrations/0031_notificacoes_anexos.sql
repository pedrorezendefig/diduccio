-- O comprovante assinado da notificação.
--
-- A carta entregue e assinada pelo morador é a prova de que a notificação
-- chegou — sem ela, a multa seguinte se apoia num registro que só o próprio
-- condomínio afirma. Por isso o anexo entra aqui, e não como enfeite.
--
-- Tabela filha, e não coluna na linha: a carta assinada volta digitalizada em
-- mais de uma folha com frequência (frente, verso, segunda página), e uma
-- coluna só forçaria escolher qual delas guardar. Mesmo desenho de
-- `entregas_foto`, que existe pelo mesmo motivo.

create table if not exists public.notificacoes_anexos (
  id              bigint generated by default as identity primary key,
  id_notificacao  bigint not null references public.notificacoes(id) on delete cascade,
  nome_arquivo    text,
  caminho_storage text not null,
  created_at      timestamptz not null default now(),
  created_by      text,
  updated_at      timestamptz not null default now()
);

-- `on delete cascade` acima é deliberado: apagar a notificação apaga as LINHAS
-- dos anexos. Os ARQUIVOS no bucket não saem por cascade — quem os apaga é a
-- tela, ANTES de apagar a linha. Apagada a linha, o caminho é irrecuperável e o
-- arquivo vira armazenamento pago que ninguém enxerga.

alter table public.notificacoes_anexos enable row level security;

drop trigger if exists trg_notificacoes_anexos_updated_at on public.notificacoes_anexos;
create trigger trg_notificacoes_anexos_updated_at before update on public.notificacoes_anexos
  for each row execute function public.tocar_updated_at();

create index if not exists idx_notificacoes_anexos_notificacao
  on public.notificacoes_anexos (id_notificacao);

-- Mesmo recorte da tabela mãe: se o porteiro não lê a descrição da conduta,
-- não pode alcançar a foto da carta que descreve a mesma conduta.
drop policy if exists notificacoes_anexos_ler    on public.notificacoes_anexos;
drop policy if exists notificacoes_anexos_criar  on public.notificacoes_anexos;
drop policy if exists notificacoes_anexos_apagar on public.notificacoes_anexos;

create policy notificacoes_anexos_ler on public.notificacoes_anexos
  for select to authenticated
  using (public.eh_administrativo());

create policy notificacoes_anexos_criar on public.notificacoes_anexos
  for insert to authenticated
  with check (public.eh_administrativo());

-- Sem policy de UPDATE: comprovante assinado não se corrige. Trocou de
-- documento, apaga e anexa outro — e apagar é do síndico.
create policy notificacoes_anexos_apagar on public.notificacoes_anexos
  for delete to authenticated
  using (public.eh_sindico());

revoke all on public.notificacoes_anexos from anon;

