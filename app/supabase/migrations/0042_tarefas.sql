-- Tarefas da administração: o quadro que o síndico e o auxiliar dividem.
--
-- Uma tabela só, compartilhada. O síndico cria e entrega ao auxiliar; o
-- auxiliar cria a sua e o síndico vê tudo. "Minhas" é filtro de tela, não
-- recorte de banco.
--
-- A situação guarda o ID em caixa alta, como `tipo` em `notificacoes`; o rótulo
-- com acento é assunto da tela.
--
-- DEPENDE DO 0015 (eh_administrativo, eh_sindico) e do 0035 (nome_atual); o
-- tocar_updated_at() já existe desde as primeiras migrações.

create table if not exists public.tarefas (
  id             bigint generated by default as identity primary key,
  titulo         text not null check (btrim(titulo) <> ''),
  descricao      text,
  situacao       text not null default 'A_FAZER'
                 check (situacao in ('A_FAZER', 'EM_ANDAMENTO', 'AGUARDANDO', 'CONCLUIDA')),
  -- Nulo quando o usuário é apagado: a tarefa sobrevive e a tela mostra "Sem
  -- responsável", em vez de sumir com o histórico de quem saiu.
  responsavel_id bigint references public.usuarios(id) on delete set null,
  prazo          date,
  id_unidade     bigint references public.unidades(id) on delete set null,
  -- As três abaixo são do gatilho. A tela não as manda: são três caminhos para
  -- mover uma tarefa (arrastar, botão, gaveta), e a data de conclusão não pode
  -- depender de qual deles foi usado.
  concluida_em   timestamptz,
  movida_em      timestamptz,
  movida_por     text,
  created_at     timestamptz not null default now(),
  created_by     text,
  updated_at     timestamptz not null default now()
);

alter table public.tarefas enable row level security;

drop trigger if exists trg_tarefas_updated_at on public.tarefas;
create trigger trg_tarefas_updated_at before update on public.tarefas
  for each row execute function public.tocar_updated_at();

create index if not exists idx_tarefas_situacao    on public.tarefas (situacao);
create index if not exists idx_tarefas_responsavel on public.tarefas (responsavel_id);
create index if not exists idx_tarefas_concluida   on public.tarefas (concluida_em);

-- ---------------------------------------------------------------------------
-- O carimbo
-- ---------------------------------------------------------------------------
-- O nome vem do token (`nome_atual()` do 0035), nunca do corpo da requisição:
-- quem tem o próprio token monta a chamada no DevTools e assinaria com o nome
-- de outro. O `coalesce` do `created_by` preserva o valor do cliente quando o
-- token não traz `usuario_id`, como no 0035.
create or replace function public.tarefas_carimbar()
returns trigger
language plpgsql
security definer
set search_path = public
as $$
begin
  if tg_op = 'INSERT' then
    new.created_by := coalesce(nullif(public.nome_atual(), ''), new.created_by);
    -- O default de created_at só vale quando o cliente omite a coluna; quem a
    -- manda forjaria a data de criação. Aqui ela é sempre a do banco.
    new.created_at := now();
    new.updated_at := now();
    new.movida_em := null;
    new.movida_por := null;
    new.concluida_em := case when new.situacao = 'CONCLUIDA' then now() else null end;
    return new;
  end if;

  -- Edição: quem criou e quando não mudam, venha o que vier do cliente.
  new.created_by := old.created_by;
  new.created_at := old.created_at;

  if new.situacao is distinct from old.situacao then
    new.movida_em := now();
    -- Diferente do created_by, sem `coalesce` de propósito: se o token não traz
    -- usuario_id, movida_por fica nulo em vez de aceitar o valor do cliente.
    new.movida_por := nullif(public.nome_atual(), '');
    new.concluida_em := case when new.situacao = 'CONCLUIDA' then now() else null end;
  else
    -- Editar o título não é mover. Sem isto, o cliente reescreveria o carimbo.
    new.movida_em := old.movida_em;
    new.movida_por := old.movida_por;
    new.concluida_em := old.concluida_em;
  end if;

  return new;
end $$;

revoke execute on function public.tarefas_carimbar() from public;
revoke execute on function public.tarefas_carimbar() from anon;

drop trigger if exists trg_tarefas_carimbar_criacao on public.tarefas;
create trigger trg_tarefas_carimbar_criacao
  before insert on public.tarefas
  for each row execute function public.tarefas_carimbar();

drop trigger if exists trg_tarefas_carimbar_edicao on public.tarefas;
create trigger trg_tarefas_carimbar_edicao
  before update on public.tarefas
  for each row execute function public.tarefas_carimbar();

-- ---------------------------------------------------------------------------
-- RLS
-- ---------------------------------------------------------------------------
-- Ler, criar e editar: a administração. Apagar: o síndico (e o dev, que está
-- dentro de `eh_sindico()`), como em toda tabela administrativa — o auxiliar
-- conclui, não apaga.
drop policy if exists tarefas_ler    on public.tarefas;
drop policy if exists tarefas_criar  on public.tarefas;
drop policy if exists tarefas_editar on public.tarefas;
drop policy if exists tarefas_apagar on public.tarefas;

create policy tarefas_ler on public.tarefas
  for select to authenticated
  using (public.eh_administrativo());

create policy tarefas_criar on public.tarefas
  for insert to authenticated
  with check (public.eh_administrativo());

-- As duas pontas por extenso: numa política de UPDATE, `using` sozinho vale
-- também como `with check` (a lição do 0039/0040).
create policy tarefas_editar on public.tarefas
  for update to authenticated
  using (public.eh_administrativo())
  with check (public.eh_administrativo());

create policy tarefas_apagar on public.tarefas
  for delete to authenticated
  using (public.eh_sindico());

revoke all on public.tarefas from anon;
